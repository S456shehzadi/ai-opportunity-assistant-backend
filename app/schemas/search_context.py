from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field

from app.ai.query.intent_schemas import SearchIntent
from app.schemas.ai_profile import NormalizedAIProfile


class ClarificationImportance(StrEnum):
    CRITICAL = "critical"  # Cannot search effectively without this (e.g. completely unconstrained)
    HELPFUL = "helpful"  # Would significantly narrow down results
    OPTIONAL = "optional"  # Nice to have


class ClarificationRequirement(BaseModel):
    field: str
    reason: str
    importance: ClarificationImportance = ClarificationImportance.HELPFUL
    suggested_options: list[str] = Field(default_factory=list)


class ConflictResolutionType(StrEnum):
    QUERY_OVERRIDE = "query_override"  # Explicit query constraint overrides profile preference
    NO_CONFLICT = "no_conflict"


class ConstraintConflict(BaseModel):
    field: str
    query_value: Any
    profile_value: Any
    resolution: ConflictResolutionType = ConflictResolutionType.QUERY_OVERRIDE
    explanation: str


class SearchQuery(BaseModel):
    """Structured web search query model designed for downstream search providers."""

    query: str
    purpose: str  # e.g., "broad_search", "no_ielts_specific", "university_portal"
    priority: int = 1  # 1 is highest priority
    source_type: str = "general_web"  # "official_portal", "university_domain", "general_web"
    required_constraints: list[str] = Field(default_factory=list)
    excluded_terms: list[str] = Field(default_factory=list)


class OpportunitySearchContext(BaseModel):
    """Unified context fusing user profile, query intent, explicit constraints,

    detected conflicts, and ambiguity requirements for search engine execution.
    """

    candidate_profile: NormalizedAIProfile
    search_intent: SearchIntent

    # Clear separation of provenance
    explicit_constraints: dict[str, Any] = Field(default_factory=dict)
    profile_constraints: dict[str, Any] = Field(default_factory=dict)
    inferred_context: dict[str, Any] = Field(default_factory=dict)

    # Auditable conflict and ambiguity handling
    conflicts: list[ConstraintConflict] = Field(default_factory=list)
    clarification_requirements: list[ClarificationRequirement] = Field(default_factory=list)
    unknown_information: list[str] = Field(default_factory=list)

    # Search queries generated by QueryOptimizer
    potential_search_queries: list[SearchQuery] = Field(default_factory=list)
